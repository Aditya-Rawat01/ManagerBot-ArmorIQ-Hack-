-- 0003_knowledge_tables.sql — protected knowledge tables (P2-01).
--
-- Toolserver-role only: the backend role is granted NOTHING on these tables
-- (PRD v2 §8.1, Arch §7.5; enforced in 0005_roles_grants.sql and proven by
-- scripts/verify_db_grants.py). Every record carries source, author,
-- timestamp, tier, review/status, version, content hash and supersession
-- metadata (PRD v2 §8.1).

CREATE TABLE IF NOT EXISTS public.source_records (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     TEXT NOT NULL,
    workspace_id  TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    source_type   TEXT NOT NULL DEFAULT 'note',
    title         TEXT NOT NULL,
    author        TEXT NOT NULL,
    reference     TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    tier          TEXT NOT NULL CHECK (tier IN ('team', 'confidential', 'restricted')),
    status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'superseded')),
    content_hash  CHAR(64) NOT NULL,
    provenance    JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (workspace_id, source_id)
);
CREATE INDEX IF NOT EXISTS source_records_tier_status_idx
    ON public.source_records (workspace_id, tier, status);

CREATE TABLE IF NOT EXISTS public.knowledge_chunks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     BIGINT NOT NULL REFERENCES public.source_records (id) ON DELETE CASCADE,
    workspace_id  TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    tier          TEXT NOT NULL CHECK (tier IN ('team', 'confidential', 'restricted')),
    chunk_text    TEXT NOT NULL,
    -- FastEmbed BAAI/bge-small-en-v1.5, 384 dims (PRD v2 §8.2). Always set by
    -- the ingestion path (P2-03); retrieval never embeds inside a handler.
    embedding     vector(384) NOT NULL,
    content_hash  CHAR(64) NOT NULL,
    content_tsv   tsvector,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, content_hash)
);

-- to_tsvector is STABLE, not IMMUTABLE, so a GENERATED column cannot use it;
-- a trigger maintains the lexical column instead.
CREATE OR REPLACE FUNCTION public.knowledge_chunks_tsv_trigger()
RETURNS trigger AS $$
BEGIN
    NEW.content_tsv := to_tsvector('english', COALESCE(NEW.chunk_text, ''));
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS knowledge_chunks_tsv ON public.knowledge_chunks;
CREATE TRIGGER knowledge_chunks_tsv
    BEFORE INSERT OR UPDATE OF chunk_text ON public.knowledge_chunks
    FOR EACH ROW EXECUTE FUNCTION public.knowledge_chunks_tsv_trigger();

CREATE INDEX IF NOT EXISTS knowledge_chunks_tsv_idx
    ON public.knowledge_chunks USING gin (content_tsv);
-- HNSW needs no training pass (unlike IVFFlat), so it serves a small,
-- growing seed corpus from the first row (vector index type: HNSW).
CREATE INDEX IF NOT EXISTS knowledge_chunks_embedding_idx
    ON public.knowledge_chunks USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);

CREATE TABLE IF NOT EXISTS public.decisions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id      TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    statement         TEXT NOT NULL,
    rationale         TEXT,
    project           TEXT,
    owner_member_id   TEXT REFERENCES public.members (id) ON DELETE RESTRICT,
    authoritative     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    superseded_by_id  BIGINT REFERENCES public.decisions (id) ON DELETE RESTRICT,
    source_id         BIGINT REFERENCES public.source_records (id) ON DELETE RESTRICT,
    version           INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1)
);

CREATE TABLE IF NOT EXISTS public.manager_guidance (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id      TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    guidance_text     TEXT NOT NULL,
    scope             TEXT NOT NULL DEFAULT 'general',
    authoritative     BOOLEAN NOT NULL DEFAULT FALSE,
    approved_by_member_id TEXT REFERENCES public.members (id) ON DELETE RESTRICT,
    provenance        JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.team_notes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id      TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    author_member_id  TEXT REFERENCES public.members (id) ON DELETE RESTRICT,
    title             TEXT,
    content           TEXT NOT NULL,
    -- PRD v2 §6.1: note or summary. Author/workspace/provenance are injected
    -- by trusted code, never caller-supplied (P2-02/P2-09).
    content_kind      TEXT NOT NULL CHECK (content_kind IN ('note', 'summary')),
    review_status     TEXT NOT NULL DEFAULT 'draft'
                      CHECK (review_status IN ('draft', 'authoritative')),
    version           INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1),
    superseded_by_id  BIGINT REFERENCES public.team_notes (id) ON DELETE RESTRICT,
    content_hash      CHAR(64) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS team_notes_review_idx
    ON public.team_notes (workspace_id, review_status);
