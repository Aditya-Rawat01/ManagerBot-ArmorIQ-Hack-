-- 0011_approved_views.sql — P2-08: company-data table and the approved
-- per-tier views (D-11, resolved 16 Oct 2026; view names final). The
-- `read_source_*` tools read ONLY these views (fixed SQL per tier, no dynamic
-- tables or columns).
--
-- Schema objects and grants only. The synthetic rows live in
-- seed/company_projects.json and are loaded by the seed ingest
-- (services/knowledge/ingest.py, migration role), which creates the
-- workspace first: a fresh `scripts/migrate.py` never depends on seeded data
-- (documented order: migrate -> login users -> ingest).
--
-- Grants travel with objects (migrations/README.md rule 3). A view runs with
-- its OWNER's privileges (no `security_invoker`), so the toolserver needs
-- SELECT on the views only and gets NOTHING on the base table, which holds
-- every tier's raw columns. The backend gets nothing on either. No runtime
-- role writes `company_projects` (verified by scripts/verify_db_grants.py).

CREATE TABLE IF NOT EXISTS public.company_projects (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    project_key   TEXT NOT NULL,
    project_name  TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'superseded')),
    tier          TEXT NOT NULL CHECK (tier IN ('team', 'confidential', 'restricted')),
    owner         TEXT NOT NULL,
    summary       TEXT NOT NULL,
    details       TEXT NOT NULL DEFAULT '',
    budget        TEXT NOT NULL DEFAULT '',
    internal_notes TEXT NOT NULL DEFAULT '',
    -- Seed upsert key (ingest: ON CONFLICT (workspace_id, project_key)).
    UNIQUE (workspace_id, project_key)
);

-- One view per tier: exact tier match plus tier-appropriate columns only.
-- Every view exposes the same shape so handlers share one fixed query.
CREATE OR REPLACE VIEW public.approved_company_data_team AS
    SELECT workspace_id, project_key, project_name, status, owner, tier,
           summary AS body
    FROM public.company_projects WHERE tier = 'team';

CREATE OR REPLACE VIEW public.approved_company_data_confidential AS
    SELECT workspace_id, project_key, project_name, status, owner, tier,
           summary || E'\nBudget: ' || budget AS body
    FROM public.company_projects WHERE tier = 'confidential';

CREATE OR REPLACE VIEW public.approved_company_data_restricted AS
    SELECT workspace_id, project_key, project_name, status, owner, tier,
           summary || E'\n' || details
               || E'\nBudget: ' || budget
               || E'\nNotes: ' || internal_notes AS body
    FROM public.company_projects WHERE tier = 'restricted';

-- Base table: no runtime role (views read it with the owner's privileges).
REVOKE ALL ON public.company_projects FROM PUBLIC;
REVOKE ALL ON public.company_projects FROM proxylead_backend;
REVOKE ALL ON public.company_projects FROM proxylead_toolserver;

-- Views: toolserver SELECT only; backend denied.
REVOKE ALL ON public.approved_company_data_team FROM PUBLIC;
REVOKE ALL ON public.approved_company_data_team FROM proxylead_backend;
GRANT SELECT ON public.approved_company_data_team TO proxylead_toolserver;
REVOKE ALL ON public.approved_company_data_confidential FROM PUBLIC;
REVOKE ALL ON public.approved_company_data_confidential FROM proxylead_backend;
GRANT SELECT ON public.approved_company_data_confidential TO proxylead_toolserver;
REVOKE ALL ON public.approved_company_data_restricted FROM PUBLIC;
REVOKE ALL ON public.approved_company_data_restricted FROM proxylead_backend;
GRANT SELECT ON public.approved_company_data_restricted TO proxylead_toolserver;
