-- 0002_core_tables.sql — app-metadata tables (P2-01).
--
-- workspaces / members (seeded by the migration role per D-20/ADR-021),
-- slack_events (backend dedupe, P3-05), topic_access_rules (manager topic
-- map, P3-02/P4-04). Enum literals match services/contracts/enums.py exactly;
-- tests/toolserver/test_migrations.py asserts every value is present.
-- Timestamps are TIMESTAMPTZ; money/secret columns do not exist anywhere here.

CREATE TABLE IF NOT EXISTS public.workspaces (
    id              TEXT PRIMARY KEY,
    name            TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.members (
    id                        TEXT PRIMARY KEY,
    workspace_id              TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    persona                   TEXT NOT NULL CHECK (persona IN ('maya', 'sam', 'priya')),
    display_name              TEXT NOT NULL,
    app_role                  TEXT NOT NULL CHECK (app_role IN ('manager', 'senior', 'junior')),
    masked_email              TEXT NOT NULL,
    slack_user_id             TEXT UNIQUE,
    -- Env-key reference (e.g. PERSONA_SAM_EMAIL), never a raw email (D-20/ADR-021).
    armoriq_member_email_ref  TEXT NOT NULL,
    active                    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS members_workspace_idx ON public.members (workspace_id);

CREATE TABLE IF NOT EXISTS public.slack_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slack_event_id  TEXT NOT NULL UNIQUE,
    workspace_id    TEXT NOT NULL,
    channel_id      TEXT,
    status          TEXT NOT NULL DEFAULT 'received'
                    CHECK (status IN ('received', 'processed')),
    received_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS slack_events_status_idx ON public.slack_events (status);

CREATE TABLE IF NOT EXISTS public.topic_access_rules (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id      TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    topic             TEXT NOT NULL,
    max_tier          TEXT NOT NULL CHECK (max_tier IN ('team', 'confidential', 'restricted')),
    source_collections JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by_member_id TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, topic)
);
