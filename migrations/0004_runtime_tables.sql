-- 0004_runtime_tables.sql — plans, approvals, audit events, ledger, queues (P2-01).
--
-- Writers: backend tables are written by apps/api (P3-01); the ledger and the
-- task/egress tables are written by the tool server only. Grants (who may
-- read/write what) live in 0005_roles_grants.sql. Delivery/decision enum
-- literals match services/contracts/enums.py exactly. Audit payloads must
-- stay redacted (no secrets, tokens, or raw emails) — enforced by writers,
-- not by the schema.

CREATE TABLE IF NOT EXISTS public.plans (
    id                  TEXT PRIMARY KEY,
    request_id          TEXT NOT NULL,
    trace_id            TEXT NOT NULL,
    workspace_id        TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    requester_member_id TEXT NOT NULL REFERENCES public.members (id) ON DELETE RESTRICT,
    entry_point         TEXT NOT NULL CHECK (entry_point IN (
                            'slack_mention', 'slack_dm', 'web')),
    armoriq_plan_id     TEXT,
    plan_hash           TEXT,
    status              TEXT NOT NULL DEFAULT 'open',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS plans_request_idx ON public.plans (request_id);

CREATE TABLE IF NOT EXISTS public.plan_steps (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id       TEXT NOT NULL REFERENCES public.plans (id) ON DELETE CASCADE,
    step_index    INTEGER NOT NULL CHECK (step_index >= 0),
    tool_name     TEXT NOT NULL,
    mcp_endpoint  TEXT NOT NULL,
    arguments     JSONB NOT NULL DEFAULT '{}'::jsonb,
    status        TEXT NOT NULL DEFAULT 'open',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (plan_id, step_index)
);

CREATE TABLE IF NOT EXISTS public.approval_requests (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id           TEXT NOT NULL REFERENCES public.plans (id) ON DELETE CASCADE,
    step_index        INTEGER NOT NULL CHECK (step_index >= 0),
    tool_name         TEXT NOT NULL,
    delegation_id     TEXT UNIQUE,
    state             TEXT NOT NULL CHECK (state IN (
                          'pending', 'approved', 'rejected', 'expired',
                          'timeout', 'interrupted', 'unverified')),
    requested_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at       TIMESTAMPTZ,
    requested_by_member_id TEXT REFERENCES public.members (id) ON DELETE RESTRICT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS approval_requests_state_idx
    ON public.approval_requests (state) WHERE resolved_at IS NULL;

CREATE TABLE IF NOT EXISTS public.request_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    TEXT NOT NULL,
    trace_id      TEXT NOT NULL,
    plan_id       TEXT REFERENCES public.plans (id) ON DELETE CASCADE,
    step_index    INTEGER,
    jti           TEXT,
    event_type    TEXT NOT NULL,
    payload       JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS request_events_request_idx
    ON public.request_events (request_id, occurred_at);

CREATE TABLE IF NOT EXISTS public.decision_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id        TEXT NOT NULL,
    trace_id          TEXT NOT NULL,
    plan_id           TEXT REFERENCES public.plans (id) ON DELETE CASCADE,
    step_index        INTEGER,
    jti               TEXT,
    event_type        TEXT NOT NULL,
    decision_source   TEXT CHECK (decision_source IN (
                          'armoriq_issuance', 'armoriq_policy_decision',
                          'armoriq_sdk_plan_check', 'armoriq_proxy_decision',
                          'tool_server_rule', 'application_rule', 'unknown')),
    delegation_id     TEXT,
    payload           JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS decision_events_request_idx
    ON public.decision_events (request_id, occurred_at);

-- Hash-chained, append-only execution ledger. P2-07 owns the chain verifier
-- and the jti idempotency rule; this table provides the columns both need.
-- NO runtime role may UPDATE or DELETE here (grants in 0005).
CREATE TABLE IF NOT EXISTS public.tool_execution_ledger (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id          TEXT NOT NULL,
    trace_id            TEXT NOT NULL,
    plan_id             TEXT,
    armoriq_plan_id     TEXT,
    step_index          INTEGER,
    tool_name           TEXT NOT NULL,
    jti                 TEXT NOT NULL UNIQUE,
    requester_member_id TEXT,
    validation_outcome  TEXT NOT NULL DEFAULT 'accepted',
    execution_status    TEXT NOT NULL CHECK (execution_status IN (
                            'executed', 'rejected_by_tool_server', 'not_reached',
                            'error', 'unknown')),
    result_id           TEXT,
    error_class         TEXT,
    prev_hash           CHAR(64) NOT NULL,
    entry_hash          CHAR(64) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ledger_request_idx
    ON public.tool_execution_ledger (request_id, step_index);

CREATE TABLE IF NOT EXISTS public.delivery_events (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id            TEXT NOT NULL,
    trace_id              TEXT NOT NULL,
    plan_id               TEXT REFERENCES public.plans (id) ON DELETE CASCADE,
    delivery_channel      TEXT CHECK (delivery_channel IN (
                              'slack_thread', 'slack_dm', 'web_private')),
    delivered_to_member_id TEXT REFERENCES public.members (id) ON DELETE RESTRICT,
    delivery_status       TEXT NOT NULL,
    delivered_at          TIMESTAMPTZ,
    occurred_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS delivery_events_request_idx
    ON public.delivery_events (request_id, occurred_at);

CREATE TABLE IF NOT EXISTS public.unanswered_questions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id            TEXT NOT NULL,
    workspace_id          TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    requester_member_id   TEXT REFERENCES public.members (id) ON DELETE RESTRICT,
    question              TEXT NOT NULL,
    status                TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'answered')),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at           TIMESTAMPTZ
);

-- Only if the corresponding tools ship (PRD v2 §8.1; D-17 for follow-up
-- tasks). Empty tables are harmless when a tool does not ship.
CREATE TABLE IF NOT EXISTS public.tasks (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id          TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    title                 VARCHAR(200) NOT NULL,
    description           TEXT,
    owner                 TEXT NOT NULL DEFAULT 'sam',
    priority              TEXT NOT NULL DEFAULT 'normal',
    idempotency_key       TEXT NOT NULL UNIQUE,
    created_by_member_id  TEXT REFERENCES public.members (id) ON DELETE RESTRICT,
    status                TEXT NOT NULL DEFAULT 'open'
                          CHECK (status IN ('open', 'done', 'cancelled')),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Honeypot sink: non-networked by construction (no channel/URL columns exist).
-- Destination is fixed to synthetic_sink (ADR-025).
CREATE TABLE IF NOT EXISTS public.egress_sink (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  TEXT NOT NULL REFERENCES public.workspaces (id) ON DELETE RESTRICT,
    request_id    TEXT,
    tool_name     TEXT NOT NULL DEFAULT 'send_external_message',
    destination   TEXT NOT NULL DEFAULT 'synthetic_sink'
                  CHECK (destination = 'synthetic_sink'),
    message       TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
